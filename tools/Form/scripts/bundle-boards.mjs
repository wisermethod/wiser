#!/usr/bin/env node
// Maintainer generator: fixed source/output paths, no dependencies or network.
import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BRAND_BOARD_CSS } from '../../Contact Sheet/scripts/brand-board-style.js';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const output = new URL('../engine/boards-lib.js', import.meta.url);
const moduleBody = source => source.replace(/^import .*;\n/gm, '').replace(/\bexport (?=(?:const|function))/g, '');
const wrap = (source, names) => `(() => {\n${moduleBody(source)}\nreturn {${names}};\n})()`;
function scoped(css) {
  // Scope the existing geometry, including its responsive rules, to board art.
  const rules = text => text.replace(/([^{}]+)\{([^{}]*)\}/g, (_, selectors, body) =>
    selectors.trim().startsWith('@') ? `${selectors}{${body}}` : `${selectors.split(',').map(s => `.board-art ${s.trim().replace(/\.tile\b/g,'.board-preview')}`).join(',')}{${body}}`);
  // Media rules contain one level of ordinary rules.
  return css.replace(/@media[^{}]+\{(?:[^{}]*\{[^{}]*\}[^{}]*)*\}|[^{}]+\{[^{}]*\}/g, block => {
    if (block.startsWith('@media')) { const i=block.indexOf('{'); return block.slice(0,i+1)+rules(block.slice(i+1,-1))+'}'; }
    return rules(block);
  });
}
export function generateBoardsLibrary() {
  const parts = JSON.parse(read('../../../skills/Build Brand/parts/parts.json'));
  // No font paths, pack hashes, downloads or curation history in the hosted library.
  const fields={pairings:['id','tags','type','handwriting'],palettes:['id','energy','paletteLoudness','tags','light','dark','swatches','modeSwatches','chips'],graphics:['id','tags','hero','pattern','texture','legend','title','description','noteArrow','sample','bannerRule'],containers:['id','svg','plate']};
  const library = Object.fromEntries(Object.entries(fields).map(([kind,keys])=>[kind,parts[kind].map(p=>Object.fromEntries(keys.filter(k=>Object.hasOwn(p,k)).map(k=>[k,p[k]])))]));
  for (const pairing of library.pairings) for (const face of [...Object.values(pairing.type),...pairing.handwriting]) delete face.files;
  let validation = read('../../Contact Sheet/scripts/brand-boards.js');
  validation = validation.slice(0,validation.indexOf('export const brandBoardsHtml'));
  const start=validation.indexOf('// Read the WOFF2 directory'), end=validation.indexOf('function face(');
  if(start<0||end<start) throw Error('Validation source seam changed; inspect the font-byte adapter.');
  validation=validation.slice(0,start)+validation.slice(end);
  const byteCheck='readAsset(asset); fontContainer(asset, `${at}.files[${i}]`);';
  if(!validation.includes(byteCheck)) throw Error('Validation font-byte seam changed.');
  validation=validation.replace(byteCheck,'readAsset(asset);').replaceAll('Buffer.from(svg)','new TextEncoder().encode(svg)');
  return `// Generated by scripts/bundle-boards.mjs; edit its sources, then regenerate.\n`+
    `const core = ${wrap(read('../../../skills/Build Brand/scripts/assemble-core.mjs'),'assembleCore,AXES,partPositions')};\n`+
    `const model = ${wrap(read('../../Contact Sheet/scripts/board-model.js'),'createBoardModel,PUBLIC_FONT_FILES,BOARD_LAYOUT,BOARD_LABELS,DEFAULT_MARK_CAPTION')};\n`+
    `const svg = ${wrap("const fail = message => { throw Error(message); };\n"+read('../../Contact Sheet/scripts/svg.js'),'checkSvg')};\n`+
    `const validation = ${wrap("const fail = message => { throw Error(message); };\nconst checkSvg = svg.checkSvg;\n"+validation,'validateBrandBoards,wcag')};\n`+
    `export const BOARD_PARTS = ${JSON.stringify(library)};\n`+
    `export const BOARD_CSS = ${JSON.stringify(scoped(BRAND_BOARD_CSS))};\n`+
    `export const {assembleCore} = core;\nexport const {createBoardModel,PUBLIC_FONT_FILES,BOARD_LAYOUT,BOARD_LABELS,DEFAULT_MARK_CAPTION} = model;\n`+
    `export const {validateBrandBoards,wcag} = validation;\nexport const {checkSvg} = svg;\n`;
}
export function main(argv=process.argv.slice(2)) {
  try {
    for(const flag of argv) if(!['help','--help','--check'].includes(flag)) throw Error(`Unknown option ${flag}; see bundle-boards.mjs --help.`);
    if(argv.includes('help')||argv.includes('--help')) { process.stdout.write('Usage: node scripts/bundle-boards.mjs [--check|--help]\nRegenerate engine/boards-lib.js from Build Brand and Contact Sheet; --check refuses drift. No installs or network.\n'); return; }
    if(argv.length>1) throw Error('Use one option; see bundle-boards.mjs --help.');
    const source=generateBoardsLibrary();
    if(argv.includes('--check')) { if(readFileSync(output,'utf8')!==source) throw Error('boards-lib.js is stale; run node scripts/bundle-boards.mjs.'); }
    else writeFileSync(output,source);
    process.stdout.write(JSON.stringify({ok:true,bytes:Buffer.byteLength(source),checked:argv.includes('--check')})+'\n');
  } catch(error) { process.stderr.write(JSON.stringify({error:error.message})+'\n');process.exitCode=1; }
}
if(process.argv[1]&&realpathSync(process.argv[1])===fileURLToPath(import.meta.url))main();
